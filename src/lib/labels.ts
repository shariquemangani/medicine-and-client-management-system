function getNestedLabel(dict: Record<string, unknown>, key: string): string | undefined {
  const value = key.split('.').reduce<unknown>((current, part) => {
    if (current && typeof current === 'object' && part in current) {
      return (current as Record<string, unknown>)[part]
    }
    return undefined
  }, dict)

  return typeof value === 'string' ? value : undefined
}

export function t(key: string, params?: Record<string, string | number>): string {
  const template = getNestedLabel(en as Record<string, unknown>, key) ?? key

  if (!params) return template

  return Object.entries(params).reduce((result, [paramKey, paramValue]) => {
    const token = `{{${paramKey}}}`
    return result.split(token).join(String(paramValue))
  }, template)
}
